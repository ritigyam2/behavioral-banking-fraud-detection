export const formatINR = (val) => {
  if (val === undefined || val === null || isNaN(val)) return "₹0.00";
  const num = Number(val);
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(num);
};

export const formatCompactINR = (val) => {
  if (!val || isNaN(val)) return "₹0";
  const num = Number(val);
  if (num >= 10000000) {
    return `₹${(num / 10000000).toFixed(2)} Cr`;
  }
  if (num >= 100000) {
    return `₹${(num / 100000).toFixed(2)} L`;
  }
  if (num >= 1000) {
    return `₹${(num / 1000).toFixed(1)}k`;
  }
  return `₹${num.toFixed(0)}`;
};

export const formatDateTime = (str) => {
  if (!str) return "—";
  try {
    const d = new Date(String(str).replace(" ", "T"));
    if (isNaN(d.getTime())) return str;
    return d.toLocaleString("en-IN", {
      year: "numeric",
      month: "short",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
  } catch {
    return str;
  }
};

export const formatTimeOnly = (str) => {
  if (!str) return "—";
  try {
    const d = new Date(String(str).replace(" ", "T"));
    if (isNaN(d.getTime())) return str;
    return d.toLocaleTimeString("en-IN", {
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
  } catch {
    return str;
  }
};

export const toTitleCase = (str) => {
  if (!str) return "None";
  return String(str)
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
};

export function RiskBadge({ level }) {
  const norm = String(level || "").toLowerCase().replace(" risk", "").trim();
  switch (norm) {
    case "critical":
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded text-xs font-semibold badge-risk-critical">
          <span className="w-1.5 h-1.5 rounded-full bg-red-600"></span>
          Critical
        </span>
      );
    case "high":
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded text-xs font-semibold badge-risk-high">
          <span className="w-1.5 h-1.5 rounded-full bg-orange-600"></span>
          High
        </span>
      );
    case "moderate":
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded text-xs font-semibold badge-risk-moderate">
          <span className="w-1.5 h-1.5 rounded-full bg-amber-600"></span>
          Moderate
        </span>
      );
    case "low":
    default:
      return (
        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded text-xs font-semibold badge-risk-low">
          <span className="w-1.5 h-1.5 rounded-full bg-emerald-600"></span>
          Low
        </span>
      );
  }
}

export function StatusBadge({ status }) {
  const norm = String(status || "Pending").toLowerCase().trim();
  switch (norm) {
    case "approved":
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium badge-status-approved">
          Approved
        </span>
      );
    case "blocked":
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium badge-status-blocked">
          Blocked
        </span>
      );
    case "escalated":
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium badge-status-escalated">
          Escalated
        </span>
      );
    case "pending":
    default:
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium badge-status-pending">
          Pending
        </span>
      );
  }
}

